import { test, expect } from './test.js'

test('React header keeps navigation context, role menu and keyboard interactions', async ({ page }) => {
  await page.goto('/e2e/fixtures/shared.html')
  await expect(page.getByRole('link', { name: 'Diagram Topologi' })).toHaveAttribute('href', '/topology?datasetId=dataset-semarang')
  const trigger = page.getByRole('button', { name: 'Menu akun Baseline Administrator' })
  await trigger.focus()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('menuitem', { name: 'Kelola pengguna' })).toBeFocused()
  await page.keyboard.press('End')
  await expect(page.getByRole('menuitem', { name: 'Keluar' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.getByRole('menuitem', { name: 'Keluar' }).click()
  await expect(page.locator('[data-logout-count]')).toHaveText('Logout: 1')
  await page.goto('/e2e/fixtures/shared.html?role=Viewer')
  await page.getByRole('button', { name: 'Menu akun Baseline Viewer' }).click()
  await expect(page.getByRole('menuitem')).toHaveCount(1)
  await expect(page.getByRole('menuitem', { name: 'Keluar' })).toBeVisible()
})

test('drawer and nested dialog maintain focus, inert state and busy protection', async ({ page }) => {
  await page.goto('/e2e/fixtures/shared.html')
  const opener = page.getByRole('button', { name: 'Tambah pengguna', exact: true })
  await opener.click()
  await expect(page.getByLabel('Username')).toBeFocused()
  await page.getByLabel('Username').fill('unsaved-draft')
  await page.getByRole('button', { name: 'Konfirmasi', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Konfirmasi perubahan' })
  await expect(dialog).toBeVisible()
  await expect(page.locator('#app')).toHaveAttribute('inert', '')
  await page.getByRole('button', { name: 'Kembali', exact: true }).focus()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('button', { name: 'Tutup dialog' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toHaveCount(0)
  await expect(page.getByRole('button', { name: 'Konfirmasi', exact: true })).toBeFocused()
  await page.getByRole('button', { name: 'Mulai proses' }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog', { name: 'Tambah pengguna' })).toHaveAttribute('aria-busy', 'true')
  await expect(page.getByLabel('Username')).toHaveValue('unsaved-draft')
  await page.getByRole('button', { name: 'Selesai' }).click()
  await page.keyboard.press('Escape')
  await expect(opener).toBeFocused()
  await expect(page.locator('#app')).not.toHaveAttribute('inert', '')
  expect(await page.evaluate(() => document.body.style.overflow)).toBe('')
})

test('shared theme and workspace controls have one update per action', async ({ page }) => {
  await page.goto('/e2e/fixtures/shared.html')
  await page.getByRole('button', { name: 'Aktifkan mode gelap' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Perbesar diagram' }).click()
  await expect(page.getByRole('button', { name: 'Kembalikan zoom ke 100%' })).toHaveText('125%')
  await page.getByRole('button', { name: 'Tampilkan seluruh diagram' }).click()
  await expect(page.getByRole('button', { name: 'Kembalikan zoom ke 100%' })).toHaveText('75%')
})

test('mobile header and nested overlays fit the viewport in dark theme', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/e2e/fixtures/shared.html')
  await page.getByRole('button', { name: 'Tambah pengguna', exact: true }).click()
  await page.getByRole('button', { name: 'Konfirmasi', exact: true }).click()
  const box = await page.getByRole('dialog', { name: 'Konfirmasi perubahan' }).boundingBox()
  expect(box.x).toBeGreaterThanOrEqual(0)
  expect(box.x + box.width).toBeLessThanOrEqual(390)
  await page.keyboard.press('Escape')
  await expect(page.getByLabel('Username')).toBeVisible()
})
